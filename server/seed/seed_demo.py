def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="python -m seed.seed_demo",
        description="Seed the demo, or repair whatever is missing. Stop the API first.",
    )
    parser.add_argument(
        "--embed-missing",
        action="store_true",
        help="embed corpus chunks the fixture lacks with OpenAI, through the AI ledger (paid)",
    )
    return parser.parse_args(argv)


def format_report(report: SeedReport) -> str:
    lines: list[str] = []
    if report.created:
        lines.append("Created: " + ", ".join(report.created))
    if report.repaired:
        lines.append("Repaired: " + ", ".join(report.repaired))
    if report.error:
        lines.append(f"Error: {report.error}")
    elif not lines:
        lines.append("The demo seed is complete; nothing to repair.")
    return "\n".join(lines)


async def main(argv: list[str] | None = None) -> int:
    from app.database import (
        close_mongo_connection,
        connect_to_mongo,
        ensure_indexes,
        get_database,
    )
    from app.rag.vector_store import get_vector_store
    from app.services.ai_clients import close_ai_clients
    from app.services.storage_service import get_storage

    args = parse_args(argv)
    await connect_to_mongo()
    try:
        await ensure_indexes()
        report = await ensure_demo_seed(
            await get_database(),
            store=get_vector_store(),
            storage=get_storage(),
            embed_missing=args.embed_missing,
        )
    finally:
        await close_mongo_connection()
        await close_ai_clients()
    print(format_report(report))
    return 0 if report.ok else 1


