# ---------------------------------------------------------------------------
# The self-healing seed
# ---------------------------------------------------------------------------
class _SeedRun:
    """One pass over the demo. Every step checks its piece and repairs what is missing.
    A run that creates the workspace is fresh: what it builds is "created". On an
    existing seed, anything it puts back is "repaired"."""

    def __init__(
        self, db: Any, store: VectorStore, storage: StorageBackend, embed_missing: bool
    ) -> None:
        self.db = db
        self.store = store
        self.storage = storage
        self.embed_missing = embed_missing
        self.report = SeedReport()
        self.fresh = False

    def note(self, item: str) -> None:
        (self.report.created if self.fresh else self.report.repaired).append(item)
        logger.info("seed: %s %s", "created" if self.fresh else "repaired", item)

    async def _workspace_doc(self, workspace_id: ObjectId) -> dict:
        doc: dict = await self.db.workspaces.find_one({"_id": workspace_id})
        return doc

    # --- user and workspace ------------------------------------------------
    async def demo_user(self) -> ObjectId:
        demo = await self.db.users.find_one({"is_demo": True})
        if demo is None:
            self.fresh = True
            now = datetime.now(timezone.utc)
            res = await self.db.users.insert_one(
                {
                    "email": settings.demo_email,
                    "hashed_password": _demo_password_hash(),
                    "full_name": settings.demo_full_name,
                    "is_active": True,
                    "is_admin": False,
                    "is_demo": True,
                    "created_at": now,
                    "updated_at": now,
                }
            )
            self.note("demo user")
            oid: ObjectId = res.inserted_id
            return oid
        if settings.environment == "production" and verify_password(
            settings.demo_password, demo["hashed_password"]
        ):
            await self.db.users.update_one(
                {"_id": demo["_id"]},
                {
                    "$set": {
                        "hashed_password": _demo_password_hash(),
                        "updated_at": datetime.now(timezone.utc),
                    }
                },
            )
            self.note("demo user password")
        existing: ObjectId = demo["_id"]
        return existing

    async def workspace(self, owner_id: ObjectId) -> dict:
        existing: dict | None = await self.db.workspaces.find_one(
            {"owner_id": owner_id, "slug": DEMO_WORKSPACE_SLUG}
        )
        if existing:
            return existing
        self.fresh = True
        now = datetime.now(timezone.utc)
        workspace_oid = ObjectId()
        doc = {
            "_id": workspace_oid,
            "owner_id": owner_id,
            "name": "Verdure Materials",
            "slug": DEMO_WORKSPACE_SLUG,
            "brand_profile": VERDURE_BRAND_PROFILE,
            "vector_namespace": str(workspace_oid),
            "embedding_model": settings.embedding_model,
            "embedding_dim": settings.embedding_dim,
            "asset_count": 0,
            "ready_chunk_count": 0,
            "created_at": now,
            "updated_at": now,
        }
        await self.db.workspaces.insert_one(doc)
        self.note("workspace")
        return doc

    # --- corpus, vectors, counts -------------------------------------------
    async def corpus(self, workspace: dict) -> dict[str, _CorpusAsset]:
        """Each corpus asset record and its stored file (re-saved from verdure_corpus/)."""
        namespace = workspace["vector_namespace"]
        out: dict[str, _CorpusAsset] = {}
        for filename, content_type, kind in CORPUS:
            path = CORPUS_DIR / filename
            if not path.is_file():
                raise SeedError(f"The corpus file seed/verdure_corpus/{filename} is missing.")
            asset = await self.db.assets.find_one(
                {"workspace_id": workspace["_id"], "filename": filename}
            )
            asset_oid = asset["_id"] if asset else ObjectId()
            key = build_storage_key(namespace, str(asset_oid), filename)
            chunks = _file_chunks(namespace, str(asset_oid), filename, content_type, kind)
            if asset is None or not await _file_exists(self.storage, key):
                await self.storage.save(key, path.read_bytes())
                if asset is not None:
                    self.note(f"file {filename}")
            now = datetime.now(timezone.utc)
            if asset is None:
                asset = {
                    "_id": asset_oid,
                    "workspace_id": workspace["_id"],
                    "filename": filename,
                    "content_type": content_type,
                    "asset_kind": kind,
                    "storage_key": key,
                    "size_bytes": path.stat().st_size,
                    "ingestion_status": "ready",
                    "chunk_count": len(chunks),
                    "error": None,
                    "ingested_at": now,
                    "created_at": now,
                    "updated_at": now,
                }
                await self.db.assets.insert_one(asset)
                self.note(f"asset {filename}")
            elif (
                asset.get("storage_key") != key
                or asset.get("ingestion_status") != "ready"
                or asset.get("chunk_count") != len(chunks)
            ):
                fix = {
                    "storage_key": key,
                    "ingestion_status": "ready",
                    "chunk_count": len(chunks),
                    "error": None,
                    "updated_at": now,
                }
                await self.db.assets.update_one({"_id": asset_oid}, {"$set": fix})
                asset.update(fix)
                self.note(f"asset {filename}")
            out[filename] = _CorpusAsset(asset, chunks)
        return out

    async def collection(self, workspace: dict, corpus: dict[str, _CorpusAsset]) -> None:
        """The vector collection holds exactly the corpus chunks, else it is dropped and
        rebuilt from the fixture. Only `embed_missing` may embed (through the ledger)."""
        namespace = workspace["vector_namespace"]
        expected = sum(a.record["chunk_count"] for a in corpus.values())
        if await self.store.count(namespace) == expected:
            return
        vectors = load_embeddings_fixture()
        chunks = [c for a in corpus.values() for c in a.chunks]
        missing = list(dict.fromkeys(c["text"] for c in chunks if chunk_key(c["text"]) not in vectors))
        if missing:
            if not self.embed_missing:
                raise SeedError(
                    f"The embeddings fixture is out of date ({len(missing)} corpus chunks have "
                    "no vector). Run python -m seed.build_embeddings_fixture --yes, or seed "
                    "once with --embed-missing (both are paid runs)."
                )
            for text, vector in zip(missing, await self._embed(missing), strict=True):
                vectors[chunk_key(text)] = vector
        await self.store.delete_workspace(namespace)
        for asset in corpus.values():
            await self.store.upsert_chunks(
                namespace, asset.chunks, [vectors[chunk_key(c["text"])] for c in asset.chunks]
            )
        self.note("vector collection")

    async def _embed(self, texts: list[str]) -> list[list[float]]:
        try:
            action = await reserve_action(
                self.db, [embedding_line("seed", texts)], visitor_id=None
            )
            async with action:
                return await embed_metered(texts, line=action.lines[0])
        except (BudgetRefusal, LiveAIUnavailable) as exc:
            raise SeedError(f"Could not embed the missing corpus chunks: {exc.message}") from exc

    async def chunk_counts(self, workspace: dict, corpus: dict[str, _CorpusAsset]) -> None:
        total = sum(a.record["chunk_count"] for a in corpus.values())
        current = await self._workspace_doc(workspace["_id"])
        if current.get("ready_chunk_count") == total and current.get("asset_count") == len(corpus):
            return
        await self.db.workspaces.update_one(
            {"_id": workspace["_id"]},
            {
                "$set": {
                    "asset_count": len(corpus),
                    "ready_chunk_count": total,
                    "updated_at": datetime.now(timezone.utc),
                }
            },
        )
        self.note("chunk counts")

    # --- brand assets and templates ----------------------------------------
    async def _set_brand(self, workspace: dict, path: str, value: object) -> None:
        await self.db.workspaces.update_one(
            {"_id": workspace["_id"]},
            {"$set": {f"brand_profile.{path}": value, "updated_at": datetime.now(timezone.utc)}},
        )

    async def logo(self, workspace: dict) -> None:
        ws_id = str(workspace["_id"])
        brand = (await self._workspace_doc(workspace["_id"])).get("brand_profile") or {}
        logo = brand.get("logo") or {}
        if logo.get("storage_key"):
            if not await _file_exists(self.storage, logo["storage_key"]):
                await self.storage.save(logo["storage_key"], _generate_logo())
                self.note("logo file")
            return
        logo_id = str(ObjectId())
        name = "verdure-logo.png"
        key = build_image_key(ws_id, logo_id, name)
        await self.storage.save(key, _generate_logo())
        url = f"/api/workspaces/{ws_id}/images/file/{logo_id}/{name}"
        await self._set_brand(workspace, "logo", {"storage_key": key, "url": url})
        self.note("logo")

    async def exemplars(self, workspace: dict) -> None:
        ws_id = str(workspace["_id"])
        brand = (await self._workspace_doc(workspace["_id"])).get("brand_profile") or {}
        existing = brand.get("exemplars") or []
        if existing:
            for i, ex in enumerate(existing):
                if not await _file_exists(self.storage, ex["storage_key"]):
                    eyebrow, headline, _ = _EXEMPLAR_CARDS[i % len(_EXEMPLAR_CARDS)]
                    await self.storage.save(ex["storage_key"], _generate_card(eyebrow, headline))
                    self.note(f"exemplar file {i + 1}")
            return
        exemplars = []
        for eyebrow, headline, note in _EXEMPLAR_CARDS:
            ex_id = str(ObjectId())
            name = f"exemplar-{ex_id}.png"
            key = build_image_key(ws_id, ex_id, name)
            await self.storage.save(key, _generate_card(eyebrow, headline))
            exemplars.append(
                {
                    "id": ex_id,
                    "storage_key": key,
                    "url": f"/api/workspaces/{ws_id}/images/file/{ex_id}/{name}",
                    "style_note": note,
                }
            )
        await self._set_brand(workspace, "exemplars", exemplars)
        self.note("exemplars")

    async def brand_images(self, workspace: dict) -> None:
        ws_id = str(workspace["_id"])
        brand = (await self._workspace_doc(workspace["_id"])).get("brand_profile") or {}
        existing = brand.get("brand_images") or []
        if existing:
            for i, img in enumerate(existing):
                if not await _file_exists(self.storage, img["storage_key"]):
                    label = _BRAND_IMAGE_LABELS[i % len(_BRAND_IMAGE_LABELS)]
                    await self.storage.save(img["storage_key"], _generate_brand_image(label))
                    self.note(f"brand image file {img.get('name') or i + 1}")
            return
        images = []
        for label in _BRAND_IMAGE_LABELS:
            img_id = str(ObjectId())
            name = f"{label.lower().replace(' ', '-')}.png"
            key = build_image_key(ws_id, img_id, name)
            await self.storage.save(key, _generate_brand_image(label))
            images.append(
                {
                    "id": img_id,
                    "storage_key": key,
                    "url": f"/api/workspaces/{ws_id}/images/file/{img_id}/{name}",
                    "name": name,
                }
            )
        await self._set_brand(workspace, "brand_images", images)
        self.note("brand images")

    async def templates(self, workspace: dict) -> None:
        ws_id = str(workspace["_id"])
        for filename, fmt, generate in _TEMPLATES:
            name = filename.replace(" ", "_")
            record = await self.db.templates.find_one(
                {"workspace_id": workspace["_id"], "name": name}
            )
            if record is not None:
                if not await _file_exists(self.storage, record["storage_key"]):
                    await self.storage.save(record["storage_key"], generate())
                    self.note(f"template file {name}")
                continue
            template_oid = ObjectId()
            key = build_template_key(ws_id, str(template_oid), filename)
            data = generate()
            await self.storage.save(key, data)
            await self.db.templates.insert_one(
                {
                    "_id": template_oid,
                    "workspace_id": workspace["_id"],
                    "owner_id": workspace["owner_id"],
                    "name": name,
                    "format": fmt,
                    "storage_key": key,
                    "placeholders": discover_placeholders(data, fmt),
                    "created_at": datetime.now(timezone.utc),
                }
            )
            self.note(f"template {name}")

    # --- examples ----------------------------------------------------------
    async def examples(self, workspace: dict, corpus: dict[str, _CorpusAsset]) -> None:
        """The four read-only examples, by `example_key`. A document example also needs
        every rendered file; a missing one is rendered again at the same key."""
        specs = load_examples()
        brand_profile = (await self._workspace_doc(workspace["_id"])).get("brand_profile") or {}
        for spec in specs:
            key = spec["example_key"]
            doc = await self.db.generations.find_one(
                {"workspace_id": workspace["_id"], "example_key": key}
            )
            if doc is None:
                await self._insert_example(workspace, spec, corpus, brand_profile)
            elif doc.get("type") == "document":
                await self._repair_document_files(workspace, doc, brand_profile)

    async def _render_document(
        self, workspace: dict, generation_id: str, document: dict, brand_profile: dict
    ) -> dict[str, dict[str, str]]:
        files = await asyncio.to_thread(
            document_service.build_document_files, document, brand_profile, {}
        )
        formats: dict[str, dict[str, str]] = {}
        for fmt, data in files.items():
            file_key = build_document_key(str(workspace["_id"]), generation_id, fmt)
            await self.storage.save(file_key, data)
            formats[fmt] = {"storage_key": file_key}
        return formats

    async def _repair_document_files(
        self, workspace: dict, doc: dict, brand_profile: dict
    ) -> None:
        generation_id = str(doc["_id"])
        output = doc.get("output") or {}
        stored = output.get("formats") or {}
        missing = [
            fmt
            for fmt in stored
            if not await _file_exists(
                self.storage, build_document_key(str(workspace["_id"]), generation_id, fmt)
            )
        ]
        if stored and not missing:
            return
        formats = await self._render_document(
            workspace, generation_id, output.get("document") or {}, brand_profile
        )
        if set(formats) != set(stored):
            await self.db.generations.update_one(
                {"_id": doc["_id"]}, {"$set": {"output.formats": formats}}
            )
        for fmt in missing or sorted(formats):
            self.note(f"example file {doc['example_key']}.{fmt}")

    async def _insert_example(
        self,
        workspace: dict,
        spec: dict[str, Any],
        corpus: dict[str, _CorpusAsset],
        brand_profile: dict,
    ) -> None:
        generation_oid = ObjectId()
        key = spec["example_key"]
        kind = spec["type"]
        meta = _resolve_retrieval(spec, corpus)  # before any file is rendered
        output: dict[str, Any]
        if kind == "text":
            output = parse_post(spec["post_text"])
        elif kind == "card":
            output = build_card_output(spec["template_id"], _card_extract(spec))
            output["accent_hex"] = spec.get("accent_hex")
        elif kind == "post_pack":
            output = build_post_pack_output(
                spec["post_text"], spec["template_id"], _card_extract(spec)
            )
            output["card"]["accent_hex"] = spec.get("accent_hex")
        elif kind == "document":
            output = document_service.build_document_output(spec["archetype"], spec["document"])
            output["formats"] = await self._render_document(
                workspace, str(generation_oid), output["document"], brand_profile
            )
        else:
            raise SeedError(f"Example {key!r} has an unknown type {kind!r}.")

        now = datetime.now(timezone.utc)
        try:
            await self.db.generations.insert_one(
                {
                    "_id": generation_oid,
                    "workspace_id": workspace["_id"],
                    "owner_id": workspace["owner_id"],
                    "type": kind,
                    "brief": spec["brief"],
                    "status": "complete",
                    "output": output,
                    "retrieved_chunk_ids": [m["chunk_id"] for m in meta],
                    "retrieval_meta": meta,
                    "model": settings.ai_model,
                    "embedding_query_model": settings.embedding_model,
                    "created_at": now,
                    "updated_at": now,
                    "is_example": True,
                    "example_key": key,
                    "session_id": None,
                }
            )
        except DuplicateKeyError:
            # Nothing may point at the files rendered for this attempt: remove them.
            await self._discard_files(workspace, generation_oid, output)
            if await self.db.generations.find_one(
                {"workspace_id": workspace["_id"], "example_key": key}, projection={"_id": 1}
            ):
                return  # this workspace has it after all
            raise SeedError(
                f"The example {key!r} could not be saved: another generation already uses "
                "its key. Remove the stale example, then run the seed again (the API "
                "rebuilds the indexes at startup)."
            ) from None
        except Exception:
            await self._discard_files(workspace, generation_oid, output)
            raise
        self.note(f"example {key}")

    async def _discard_files(self, workspace: dict, generation_oid: ObjectId, output: dict) -> None:
        if output.get("formats"):
            await self.storage.delete_prefix(
                build_document_prefix(str(workspace["_id"]), str(generation_oid))
            )


def _card_extract(spec: dict[str, Any]) -> dict[str, Any]:
    return {**spec["fields"], "suggested_keywords": spec.get("suggested_keywords") or []}


def _resolve_retrieval(spec: dict[str, Any], corpus: dict[str, _CorpusAsset]) -> list[dict]:
    """The example's retrieval snapshot, resolved to the seeded asset and chunk IDs."""
    meta: list[dict] = []
    for ref in spec.get("retrieval") or []:
        asset = corpus.get(ref["filename"])
        index = int(ref["chunk_index"])
        chunk = next(
            (c for c in (asset.chunks if asset else []) if c["metadata"]["chunk_index"] == index),
            None,
        )
        if asset is None or chunk is None:
            raise SeedError(
                f"Example {spec['example_key']!r} names a chunk that does not exist: "
                f"{ref['filename']} #{index}."
            )
        asset_id = str(asset.record["_id"])
        meta.append(
            {
                "chunk_id": f"{asset_id}:{index}",
                "asset_id": asset_id,
                "filename": ref["filename"],
                "asset_kind": asset.record["asset_kind"],
                "score": float(ref["score"]),
                "preview": chunk["text"][:PREVIEW_CHARS],
                "chunk_index": index,
                "page": chunk["metadata"].get("page"),
                "pinned": bool(ref.get("pinned", False)),
            }
        )
    return meta


async def ensure_demo_seed(
    db: Any, *, store: VectorStore, storage: StorageBackend, embed_missing: bool = False
) -> SeedReport:
    """Check every piece of the demo, in order, and build or repair what is missing:
    the demo user, the workspace, each corpus asset and its file, the vector collection,
    the chunk counts, the logo, exemplars, brand images, templates, and the four examples.
    A `SeedError` stops the run and is returned as the report's `error`."""
    run = _SeedRun(db, store, storage, embed_missing)
    try:
        owner_id = await run.demo_user()
        workspace = await run.workspace(owner_id)
        corpus = await run.corpus(workspace)
        await run.collection(workspace, corpus)
        await run.chunk_counts(workspace, corpus)
        await run.logo(workspace)
        await run.exemplars(workspace)
        await run.brand_images(workspace)
        await run.templates(workspace)
        await run.examples(workspace, corpus)
    except SeedError as exc:
        run.report.error = str(exc)
        logger.error("seed: %s", exc)
    return run.report


