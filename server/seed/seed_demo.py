"""The demo seed: the demo user, the Verdure Materials workspace with its brand corpus
pre-ingested (DECISIONS #15: visitors get the RAG result at once), the brand assets and
templates, and four read-only example generations.

`ensure_demo_seed` builds all of it on a fresh database and, on a seeded one, checks each
piece and repairs what is missing: records, stored files, the vector collection, and the
examples. The app runs it at startup when SEED_ON_STARTUP is set; the CLI runs it on
demand and prints what it created or repaired:

    cd server && .venv/bin/python -m seed.seed_demo [--embed-missing]

(or `npm run seed` from the repo root). Chroma runs in-process and only one process may
open its directory, so stop the API first.

The corpus vectors come from a checked-in fixture (seed/fixtures/verdure_embeddings.json),
so seeding makes no OpenAI call and needs no key. If the corpus or the chunker changes,
rebuild the fixture with `python -m seed.build_embeddings_fixture --yes` (a paid run), or
seed once with --embed-missing, which embeds only the chunks the fixture lacks, through
the AI ledger (also a paid run). The examples come from seed/fixtures/examples.json.
"""
